        function startCountdown(selector) {
          const el = document.querySelector(selector);
          if (!el) return;
    
          let [minutes, seconds] = el.textContent.split(":").map(v => parseInt(v.trim(), 10));
          let totalSeconds = minutes * 60 + seconds;
        
          const timer = setInterval(() => {
            if (totalSeconds <= 0) {
              clearInterval(timer);
              el.textContent = "00 : 00"; 
              return;
            }
        
            totalSeconds--;
        
            let m = Math.floor(totalSeconds / 60);
            let s = totalSeconds % 60;

            m = m < 10 ? "0" + m : m;
            s = s < 10 ? "0" + s : s;
        
            el.textContent = `${m} : ${s}`;
          }, 1000);
        }

        window.onload = () => startCountdown(".time4");
        </script>
